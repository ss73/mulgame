export type Lang = 'en' | 'sv';
const dictionaries: Record<Lang, Record<Key, string>> = { en, sv };
let current: Lang = 'en';

export function detectLanguage(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.toLowerCase().split('-')[0];
    if (base === 'sv' || base === 'en') return base;
  }
  return 'en';
}

export function setLanguage(setting: Lang | 'auto'): void {
  current = setting === 'auto' ? detectLanguage() : setting;
  document.documentElement.lang = current;
  document.title = t('appName');
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? `{${p}}`));
}
